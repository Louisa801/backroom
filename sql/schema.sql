-- Backroom database schema (PostgreSQL 17)
-- Safe to run repeatedly: drops and recreates all tables.
-- Reset: psql $env:DATABASE_URL -f sql/schema.sql -f sql/seed.sql

SET client_min_messages = warning;  -- hide "table does not exist, skipping" notices

DROP TABLE IF EXISTS sales, request_items, tryon_requests, items, buy_ins, categories, staff_users CASCADE;

-- Staff and manager share one login in the MVP.
CREATE TABLE staff_users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         TEXT NOT NULL UNIQUE CHECK (email = lower(email) AND position('@' IN email) > 1),
    password_hash TEXT NOT NULL,
    name          TEXT NOT NULL CHECK (length(trim(name)) > 0)
);

CREATE TABLE categories (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (length(trim(name)) > 0)
);

-- One visit from a walk-in seller. cash_amount = sum of the items' purchase prices
-- (checked in PHP, cannot be enforced here). Store credit = cash x 1.2.
CREATE TABLE buy_ins (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id      INTEGER NOT NULL REFERENCES staff_users(id),
    payout_type   TEXT NOT NULL CHECK (payout_type IN ('cash', 'store_credit')),
    cash_amount   NUMERIC(8,2) NOT NULL CHECK (cash_amount >= 0),
    payout_amount NUMERIC(8,2) NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT buy_ins_payout_matches_type CHECK (
        (payout_type = 'cash'         AND payout_amount = cash_amount)
     OR (payout_type = 'store_credit' AND payout_amount = round(cash_amount * 1.2, 2))
    )
);

-- The buy-in date (buy_ins.created_at) is the start of the slow-mover clock.
CREATE TABLE items (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buy_in_id      INTEGER NOT NULL REFERENCES buy_ins(id),
    category_id    INTEGER NOT NULL REFERENCES categories(id),
    title          TEXT NOT NULL CHECK (length(trim(title)) > 0),
    size           TEXT NOT NULL CHECK (size IN ('XS', 'S', 'M', 'L', 'XL', 'XXL')),
    colour         TEXT NOT NULL CHECK (colour IN ('black', 'white', 'grey', 'navy', 'blue',
                                                   'green', 'red', 'pink', 'beige', 'brown')),
    condition      TEXT NOT NULL CHECK (condition IN ('like_new', 'good', 'fair')),
    purchase_price NUMERIC(8,2) NOT NULL CHECK (purchase_price >= 0),
    sale_price     NUMERIC(8,2) NOT NULL CHECK (sale_price > 0),
    photo_path     TEXT NOT NULL CHECK (length(trim(photo_path)) > 0),
    shelf_code     TEXT NOT NULL CHECK (shelf_code ~ '^[A-Z]-[0-9]{2}$'),
    status         TEXT NOT NULL DEFAULT 'in_archive'
                   CHECK (status IN ('in_archive', 'requested', 'in_fitting_room', 'sold')),
    CONSTRAINT items_sale_not_below_purchase CHECK (sale_price >= purchase_price)
);

-- A shelf spot holds one unsold item; a sold item frees its spot.
CREATE UNIQUE INDEX items_shelf_code_unsold ON items (shelf_code) WHERE status <> 'sold';
CREATE INDEX items_status ON items (status);
CREATE INDEX items_buy_in ON items (buy_in_id);

-- Status flow: new -> fetching -> ready -> closed. ready_at is set when items reach the room.
CREATE TABLE tryon_requests (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fitting_room SMALLINT NOT NULL CHECK (fitting_room BETWEEN 1 AND 3),
    status       TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'fetching', 'ready', 'closed')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    ready_at     TIMESTAMPTZ,
    closed_at    TIMESTAMPTZ,
    CONSTRAINT tryon_ready_at_matches_status  CHECK ((status IN ('ready', 'closed')) = (ready_at IS NOT NULL)),
    CONSTRAINT tryon_closed_at_matches_status CHECK ((status = 'closed') = (closed_at IS NOT NULL)),
    CONSTRAINT tryon_times_in_order CHECK (ready_at >= created_at AND closed_at >= ready_at)
);

CREATE INDEX tryon_requests_status ON tryon_requests (status, created_at);

-- Items in a request. outcome stays NULL until staff press "Sold" or "Back to archive".
CREATE TABLE request_items (
    request_id INTEGER NOT NULL REFERENCES tryon_requests(id),
    item_id    INTEGER NOT NULL REFERENCES items(id),
    outcome    TEXT CHECK (outcome IN ('sold', 'returned')),
    PRIMARY KEY (request_id, item_id)
);

CREATE INDEX request_items_item ON request_items (item_id);

-- Every sale comes from a fitting room, so it must match a request item.
CREATE TABLE sales (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id    INTEGER NOT NULL UNIQUE REFERENCES items(id),
    request_id INTEGER NOT NULL,
    sold_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    price      NUMERIC(8,2) NOT NULL CHECK (price > 0),
    FOREIGN KEY (request_id, item_id) REFERENCES request_items(request_id, item_id)
);

CREATE INDEX sales_sold_at ON sales (sold_at);
